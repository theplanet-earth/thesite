// The globe of the home page (docs/index.html): an ocean sphere lit by four lights, the land
// drawn as dots, a halo, and the places of docs/_data/coverage.yml as pulsing rings. esbuild
// bundles it with three.js into docs/assets/bundle/globe.js (scripts/bundle.sh).
//
// After "How we built the GitHub globe" by Tobias Ahlin (GitHub, 2020):
// https://github.blog/engineering/engineering-principles/how-we-built-the-github-globe/
// From the article: no texture, a few lights on a sphere; the land as about 12,000 five-sided
// circles in one InstancedMesh, placed by reading a small world map with getImageData; the
// circles fading towards the edge of the globe; a halo drawn by a shader on the back side of a
// sphere 1.15 times larger; antialiasing off; the first longitude from the time zone; a
// placeholder cross-faded into the canvas with the Web Animations API; lower quality when the
// frame rate falls under 55.5 over 50 frames; a landing ring that grows and fades. Not from
// the article: rotation by drag and by keyboard, the pause while the globe is off-screen or
// the tab hidden, and prefers-reduced-motion. The colours are those of the mascot of the logo.

import {
  AdditiveBlending,
  AmbientLight,
  AnimationMixer,
  BackSide,
  Box3,
  BufferAttribute,
  CircleGeometry,
  Color,
  DataTexture,
  DirectionalLight,
  Group,
  InstancedMesh,
  Matrix3,
  Matrix4,
  Mesh,
  MeshBasicMaterial,
  MeshPhongMaterial,
  NearestFilter,
  Object3D,
  PerspectiveCamera,
  Quaternion,
  RingGeometry,
  Scene,
  ShaderMaterial,
  SphereGeometry,
  Vector3,
  WebGLRenderer,
} from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';

import { DEG, FrameMonitor, TIERS, fitBody, landDots, rowsFor, startLongitude, toCartesian } from './geometry.js';

const RADIUS = 1;
const TILT = 0.35; // radians, to show a little more of the northern hemisphere
const SPIN = 0.06; // radians a second
const MAX_FLING = 3; // radians a second, the most a drag can throw the globe
const COLORS = {
  ocean: 0x1f5fae, // the blue of the mascot
  land: 0x9ccc65, // its green
  halo: 0x7fc8ff,
  place: 0xffa94d, // the orange of its glasses
};
const FORWARD = new Vector3(0, 0, 1);
// The mascot (docs/assets/models/mascot/, generated by Meshy from the logo): the bones whose
// vertices make its round body, how far from it the globe may replace the skin, and the turn
// that shows it three quarters on.
const BODY_BONES = new Set(['Head', 'headfront']);
const BODY_REACH = 1.35; // vertices within this share of the radius of the body take the globe
const MASCOT_TURN = -0.45;

// The dots fade towards the edge of the globe, where they crowd and shimmer (moiré).
const DOT_SHADER = {
  vertexShader: /* glsl */ `
    varying float vFacing;
    void main() {
      vec4 center = modelViewMatrix * instanceMatrix * vec4(0.0, 0.0, 0.0, 1.0);
      vec3 outward = normalize(normalMatrix * (instanceMatrix * vec4(0.0, 0.0, 0.0, 1.0)).xyz);
      vFacing = dot(outward, normalize(-center.xyz));
      gl_Position = projectionMatrix * modelViewMatrix * instanceMatrix * vec4(position, 1.0);
    }`,
  fragmentShader: /* glsl */ `
    uniform vec3 color;
    varying float vFacing;
    void main() {
      gl_FragColor = vec4(color, smoothstep(0.0, 0.4, vFacing));
      #include <colorspace_fragment>
    }`,
};

// The halo: the back faces of a larger sphere, brightest next to the globe and fading out.
const HALO_SHADER = {
  vertexShader: /* glsl */ `
    varying vec3 vNormal;
    void main() {
      vNormal = normalize(normalMatrix * normal);
      gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
    }`,
  fragmentShader: /* glsl */ `
    uniform vec3 color;
    varying vec3 vNormal;
    void main() {
      float rim = clamp(-vNormal.z, 0.0, 1.0);
      gl_FragColor = vec4(color, 1.0) * pow(rim * 2.0, 2.5) * 1.1;
      #include <colorspace_fragment>
    }`,
};

function readMask(url) {
  return new Promise((resolve, reject) => {
    const image = new Image();
    image.onload = () => {
      const canvas = document.createElement('canvas');
      canvas.width = image.naturalWidth;
      canvas.height = image.naturalHeight;
      const context = canvas.getContext('2d', { willReadFrequently: true });
      context.drawImage(image, 0, 0);
      resolve(context.getImageData(0, 0, canvas.width, canvas.height));
    };
    image.onerror = () => reject(new Error(`land mask not loaded: ${url}`));
    image.src = url;
  });
}

function readPlaces() {
  try {
    const places = JSON.parse(document.getElementById('coverage')?.textContent || '[]');
    return Array.isArray(places) ? places.filter((p) => Number.isFinite(p.lat) && Number.isFinite(p.lon)) : [];
  } catch {
    return [];
  }
}

// Puts an object on the surface at lat, lon, facing outwards (its +Z along the normal).
function place(object, lat, lon, radius) {
  const position = new Vector3(...toCartesian(lat, lon, radius));
  object.position.copy(position);
  object.quaternion.setFromUnitVectors(FORWARD, position.normalize());
  return object;
}

function dotsMesh(mask, rows) {
  const dots = landDots(mask, rows);
  const spacing = (Math.PI * RADIUS) / rows;
  const geometry = new CircleGeometry(spacing * 0.36, 5);
  const material = new ShaderMaterial({
    ...DOT_SHADER,
    uniforms: { color: { value: new Color(COLORS.land) } },
    transparent: true,
    depthWrite: false,
  });
  const mesh = new InstancedMesh(geometry, material, dots.length);
  const dummy = new Object3D();
  dots.forEach(([lat, lon], index) => {
    place(dummy, lat, lon, RADIUS * 1.001).updateMatrix();
    mesh.setMatrixAt(index, dummy.matrix);
  });
  mesh.instanceMatrix.needsUpdate = true;
  return mesh;
}

function placesGroup(places) {
  const group = new Group();
  const rings = [];
  for (const { lat, lon } of places) {
    const dot = new Mesh(new CircleGeometry(0.014, 24), new MeshBasicMaterial({ color: COLORS.place }));
    const ring = new Mesh(
      new RingGeometry(0.016, 0.022, 48),
      new MeshBasicMaterial({ color: COLORS.place, transparent: true, depthWrite: false }),
    );
    group.add(place(dot, lat, lon, RADIUS * 1.003), place(ring, lat, lon, RADIUS * 1.004));
    rings.push(ring);
  }
  return { group, rings };
}

// Frames a sphere (the globe with its halo, or the mascot) in the canvas.
function fit(camera, width, height, { center, radius }) {
  camera.aspect = width / height;
  const vertical = camera.fov * DEG;
  const horizontal = 2 * Math.atan(Math.tan(vertical / 2) * camera.aspect);
  camera.position.set(center.x, center.y, center.z + radius / Math.sin(Math.min(vertical, horizontal) / 2));
  camera.lookAt(center);
  camera.updateProjectionMatrix();
}

// The skin of the body of the mascot becomes the globe: on the fragments of its body bones whose
// texture is the light blue of its skin or the green of its painted continents, the colour is
// replaced by the dots of the land of the globe, computed per pixel with the rows of landDots
// and the same land mask; eyes, smile, glasses and cap keep their own colours. The direction of
// a fragment from the centre of the body, in the rest pose, places it on the Earth, so that the
// globe stays on the body while the mascot walks, and turns when the globe is dragged.
const BODY_GLSL = /* glsl */ `
  uniform mat3 uEarth;
  uniform sampler2D uLand;
  uniform float uRows;
  uniform vec3 uOcean;
  uniform vec3 uLandColor;
  uniform vec3 uPlaceColor;
  uniform vec3 uPlaces[4];
  uniform int uPlaceCount;
  uniform float uPhase;
  varying vec3 vBody;

  bool isSkin(vec3 linear) {
    vec3 c = pow(max(linear, vec3(0.0)), vec3(1.0 / 2.2));
    float hi = max(c.r, max(c.g, c.b));
    float lo = min(c.r, min(c.g, c.b));
    float d = hi - lo;
    if (hi < 0.55 || d / hi < 0.2) return false;
    float h = hi == c.r ? mod((c.g - c.b) / d, 6.0) : hi == c.g ? (c.b - c.r) / d + 2.0 : (c.r - c.g) / d + 4.0;
    h *= 60.0;
    return (h > 165.0 && h < 225.0 && hi > 0.62) || (h > 55.0 && h < 130.0);
  }

  vec3 globeColor(vec3 d) {
    const float PI = 3.14159265;
    vec3 e = uEarth * d;
    float lat = asin(clamp(e.y, -1.0, 1.0));
    float lon = atan(e.x, e.z);
    float spacing = PI / uRows;
    float row = clamp(floor((PI * 0.5 - lat) / spacing), 0.0, uRows - 1.0);
    float latC = PI * 0.5 - (row + 0.5) * spacing;
    float count = max(1.0, floor(2.0 * uRows * cos(latC) + 0.5));
    float column = floor((lon + PI) / (2.0 * PI) * count);
    float lonC = -PI + (column + 0.5) * 2.0 * PI / count;
    float land = step(0.5, texture2D(uLand, vec2((lonC + PI) / (2.0 * PI), (PI * 0.5 - latC) / PI)).r);
    float dist = length(vec2(lat - latC, (lon - lonC) * cos(latC))) / spacing;
    float aa = fwidth(dist);
    vec3 color = mix(uOcean, uLandColor, land * (1.0 - smoothstep(0.36 - aa, 0.36 + aa, dist)));
    for (int k = 0; k < 4; k++) {
      if (k >= uPlaceCount) break;
      float angle = acos(clamp(dot(e, uPlaces[k]), -1.0, 1.0)) / spacing;
      float fa = fwidth(angle);
      float centre = 1.0 - smoothstep(0.9 - fa, 0.9 + fa, angle);
      float ring = (1.0 - smoothstep(0.3 - fa, 0.3 + fa, abs(angle - 1.3 - uPhase * 3.5))) * (1.0 - uPhase);
      color = mix(color, uPlaceColor, max(centre, ring));
    }
    return color;
  }
`;

// Loads the mascot, finds the sphere of its body (fitted to the vertices of its body bones in
// the rest pose) and gives its material the globe; returns what the scene needs to drive it.
// Each vertex near the body gets its direction from the centre of the body in the rest pose,
// as the attribute bodyDirection (zero elsewhere): the shader places it on the Earth with it,
// whatever bone moves the vertex.
async function loadMascot(url, { mask, places }) {
  const gltf = await new GLTFLoader().loadAsync(url);
  let skinned = null;
  gltf.scene.traverse((object) => {
    if (object.isSkinnedMesh && !skinned) skinned = object;
  });
  const { bones } = skinned?.skeleton ?? { bones: [] };
  const head = bones.find((bone) => bone.name === 'Head');
  if (!skinned || !head || !gltf.animations.length) throw new Error('mascot: no skinned mesh, Head bone or animation');
  gltf.scene.updateMatrixWorld(true);
  const { position, skinIndex, skinWeight } = skinned.geometry.attributes;
  const rest = new Float32Array(position.count * 3);
  const bodyPoints = [];
  const vertex = new Vector3();
  for (let i = 0; i < position.count; i += 1) {
    skinned.getVertexPosition(i, vertex).applyMatrix4(skinned.matrixWorld);
    vertex.toArray(rest, i * 3);
    let joint = 0;
    let weight = -1;
    for (let k = 0; k < 4; k += 1) {
      if (skinWeight.getComponent(i, k) > weight) {
        weight = skinWeight.getComponent(i, k);
        joint = skinIndex.getComponent(i, k);
      }
    }
    if (BODY_BONES.has(bones[joint]?.name)) bodyPoints.push([vertex.x, vertex.y, vertex.z]);
  }
  const body = fitBody(bodyPoints);
  const directions = new Float32Array(position.count * 3);
  for (let i = 0; i < position.count; i += 1) {
    vertex.fromArray(rest, i * 3).sub(new Vector3(...body.center));
    if (vertex.length() < body.radius * BODY_REACH) vertex.normalize().toArray(directions, i * 3);
  }
  skinned.geometry.setAttribute('bodyDirection', new BufferAttribute(directions, 3));

  const land = new DataTexture(mask.data, mask.width, mask.height);
  land.magFilter = NearestFilter;
  land.minFilter = NearestFilter;
  land.needsUpdate = true;
  const uniforms = {
    uEarth: { value: new Matrix3() },
    uLand: { value: land },
    uRows: { value: 90 },
    uOcean: { value: new Color(COLORS.ocean) },
    uLandColor: { value: new Color(COLORS.land) },
    uPlaceColor: { value: new Color(COLORS.place) },
    uPlaces: { value: [0, 1, 2, 3].map((k) => (places[k] ? new Vector3(...toCartesian(places[k].lat, places[k].lon, 1)) : new Vector3())) },
    uPlaceCount: { value: Math.min(4, places.length) },
    uPhase: { value: 0 },
  };
  for (const material of [skinned.material].flat()) {
    material.onBeforeCompile = (shader) => {
      Object.assign(shader.uniforms, uniforms);
      shader.vertexShader = `attribute vec3 bodyDirection;\nvarying vec3 vBody;\n${shader.vertexShader.replace(
        '#include <begin_vertex>',
        '#include <begin_vertex>\n  vBody = bodyDirection;',
      )}`;
      shader.fragmentShader = `${BODY_GLSL}\n${shader.fragmentShader.replace(
        '#include <map_fragment>',
        `#include <map_fragment>
  if (dot(vBody, vBody) > 0.25 && isSkin(diffuseColor.rgb)) {
    diffuseColor.rgb = globeColor(normalize(vBody));
  }`,
      )}`;
    };
    material.needsUpdate = true;
  }
  return { gltf, head, body, uniforms };
}

async function start(container) {
  const placeholder = container.querySelector('.globe-placeholder');
  const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const mask = await readMask(container.dataset.land);

  const renderer = new WebGLRenderer({ antialias: false, alpha: true, powerPreference: 'high-performance' });
  let tier = 0;
  renderer.setPixelRatio(Math.min(window.devicePixelRatio || 1, TIERS[tier].pixelRatio));
  const canvas = renderer.domElement;
  canvas.setAttribute('role', 'img');
  canvas.setAttribute('aria-label', container.dataset.label || 'A globe of the Earth, with the land drawn as dots');
  canvas.tabIndex = 0;
  canvas.style.opacity = '0';
  container.append(canvas);

  const scene = new Scene();
  const camera = new PerspectiveCamera(30, 1, 0.1, 100);
  // Four lights and no texture: ambient, a key light from the upper left, a rim from behind
  // on the right, a dim blue fill from below.
  const light = (color, intensity, x, y, z) => {
    const directional = new DirectionalLight(color, intensity);
    directional.position.set(x, y, z);
    return directional;
  };
  scene.add(
    new AmbientLight(0xffffff, 0.35),
    light(0xffffff, 2.2, -3, 2, 4),
    light(COLORS.halo, 1.2, 4, 1, -1),
    light(0x3949ab, 0.8, 0, -4, 2),
  );

  const tilt = new Group();
  const spin = new Group();
  tilt.rotation.x = TILT;
  spin.rotation.y = -startLongitude(new Date().getTimezoneOffset()) * DEG;
  tilt.add(spin);
  scene.add(tilt);

  spin.add(new Mesh(new SphereGeometry(RADIUS, 96, 64), new MeshPhongMaterial({ color: COLORS.ocean, shininess: 12 })));
  const halo = new Mesh(
    new SphereGeometry(RADIUS, 96, 64),
    new ShaderMaterial({
      ...HALO_SHADER,
      uniforms: { color: { value: new Color(COLORS.halo) } },
      side: BackSide,
      blending: AdditiveBlending,
      transparent: true,
      depthWrite: false,
    }),
  );
  halo.scale.setScalar(1.15);
  scene.add(halo);

  let dots = dotsMesh(mask, TIERS[tier].rows);
  spin.add(dots);
  // The rows of dots: those of the quality tier, fewer when the globe is small on screen.
  const globeRadius = RADIUS; // in world units
  const rebuildDots = () => {
    const { clientHeight: height } = container;
    const distance = camera.position.distanceTo(framing.center);
    const pixels = (globeRadius / (distance * Math.tan((camera.fov * DEG) / 2))) * (height / 2);
    const rows = rowsFor(pixels, { max: TIERS[tier].rows });
    if (rows === dots.userData.rows) return;
    spin.remove(dots);
    dots.geometry.dispose();
    dots.material.dispose();
    dots = dotsMesh(mask, rows);
    dots.userData.rows = rows;
    spin.add(dots);
    container.dataset.dots = String(dots.count);
  };
  const { group: placesMesh, rings } = placesGroup(readPlaces());
  spin.add(placesMesh);
  container.dataset.dots = String(dots.count);
  container.dataset.tier = String(tier);
  container.dataset.state = 'globe';

  // What the camera frames: the globe with its halo, then the mascot once it has loaded.
  let framing = { center: new Vector3(), radius: RADIUS * 1.2 };
  let mixer = null;
  let mascot = null;
  const resize = () => {
    const { clientWidth: width, clientHeight: height } = container;
    if (!width || !height) return;
    renderer.setSize(width, height, false);
    fit(camera, width, height, framing);
  };
  resize();
  new ResizeObserver(resize).observe(container);

  // Rotation by drag (with a little inertia) and by the arrow keys.
  let drag = null;
  let velocity = 0;
  canvas.addEventListener('pointerdown', (event) => {
    drag = { x: event.clientX, y: event.clientY, t: performance.now() };
    velocity = 0;
    canvas.setPointerCapture(event.pointerId);
  });
  canvas.addEventListener('pointermove', (event) => {
    if (!drag) return;
    const perPixel = Math.PI / Math.max(1, canvas.clientWidth);
    const dx = (event.clientX - drag.x) * perPixel;
    const now = performance.now();
    spin.rotation.y += dx;
    tilt.rotation.x = Math.min(1.1, Math.max(-0.6, tilt.rotation.x + (event.clientY - drag.y) * perPixel));
    // Inertia: the speed of the last move, at most MAX_FLING radians a second, so that
    // pointer events a few milliseconds apart do not send the globe spinning.
    const speed = (dx / Math.max(8, now - drag.t)) * 1000;
    velocity = Math.min(MAX_FLING, Math.max(-MAX_FLING, speed));
    drag = { x: event.clientX, y: event.clientY, t: now };
  });
  const release = () => {
    if (drag && performance.now() - drag.t > 80) velocity = 0; // held still before the release
    drag = null;
  };
  canvas.addEventListener('pointerup', release);
  canvas.addEventListener('pointercancel', release);
  canvas.addEventListener('keydown', (event) => {
    const step = 10 * DEG;
    const moves = {
      ArrowLeft: () => (spin.rotation.y -= step),
      ArrowRight: () => (spin.rotation.y += step),
      ArrowUp: () => (tilt.rotation.x = Math.max(-0.6, tilt.rotation.x - step)),
      ArrowDown: () => (tilt.rotation.x = Math.min(1.1, tilt.rotation.x + step)),
    };
    if (moves[event.key]) {
      moves[event.key]();
      event.preventDefault();
    }
  });

  const monitor = new FrameMonitor();
  let last = null;
  let shown = false;
  const frame = (time) => {
    const seconds = last === null ? 0 : Math.min(0.1, (time - last) / 1000);
    if (last !== null && monitor.record(time - last) && tier < TIERS.length - 1) {
      tier += 1;
      renderer.setPixelRatio(Math.min(window.devicePixelRatio || 1, TIERS[tier].pixelRatio));
      resize();
      rebuildDots();
      container.dataset.tier = String(tier);
    }
    last = time;
    if (!drag) {
      spin.rotation.y += (reducedMotion ? 0 : SPIN) * seconds + velocity * seconds;
      velocity *= Math.pow(0.05, seconds);
    }
    if (!reducedMotion) {
      const phase = (time / 2000) % 1;
      for (const ring of rings) {
        ring.scale.setScalar(1 + phase * 3);
        ring.material.opacity = 1 - phase;
      }
    }
    mixer?.update(reducedMotion ? 0 : seconds);
    mascot?.update((time / 2000) % 1);
    renderer.render(scene, camera);
    if (!shown) {
      shown = true;
      const duration = reducedMotion ? 0 : 800;
      canvas.animate([{ opacity: 0 }, { opacity: 1 }], { duration, easing: 'ease-out', fill: 'forwards' });
      placeholder?.animate([{ opacity: 1 }, { opacity: 0 }], { duration, fill: 'forwards' }).finished.then(() => placeholder.remove());
      container.classList.add('globe--ready');
    }
  };

  // Draw only while the globe is on screen and the tab visible.
  let onScreen = true;
  const update = () => {
    const active = onScreen && !document.hidden;
    if (!active) {
      last = null;
      monitor.reset();
    }
    renderer.setAnimationLoop(active ? frame : null);
  };
  new IntersectionObserver((entries) => {
    onScreen = entries.some((entry) => entry.isIntersecting);
    update();
  }).observe(container);
  document.addEventListener('visibilitychange', update);
  update();

  // The mascot: the globe becomes its body. Until it loads, or when it cannot, the globe
  // stays alone.
  if (container.dataset.mascot) {
    await addMascot(container.dataset.mascot).catch((error) => console.warn(`globe: ${error.message}`));
  }

  async function addMascot(url) {
    const { gltf, head, body, uniforms } = await loadMascot(url, { mask, places: readPlaces() });
    const fade = (from, to) => canvas.animate([{ opacity: from }, { opacity: to }], { duration: reducedMotion ? 0 : 250, fill: 'forwards' }).finished;
    await fade(1, 0);
    const character = gltf.scene;
    character.rotation.y = MASCOT_TURN;
    scene.add(character);
    character.updateMatrixWorld(true);
    // The globe alone leaves the scene: its groups still hold the turn of the Earth, which the
    // body of the mascot now shows. The halo follows the body, as a child of the Head bone.
    scene.remove(tilt);
    const anchor = new Object3D();
    const target = new Matrix4().compose(new Vector3(...body.center).applyMatrix4(character.matrixWorld), new Quaternion(), new Vector3().setScalar(body.radius));
    anchor.applyMatrix4(head.matrixWorld.clone().invert().multiply(target));
    head.add(anchor);
    anchor.add(halo);
    mixer = new AnimationMixer(character);
    mixer.clipAction(gltf.animations[0]).play();
    mixer.update(0);
    const box = new Box3().setFromObject(character, true);
    framing = { center: box.getCenter(new Vector3()), radius: (box.getSize(new Vector3()).length() / 2) * 0.92 };
    resize();
    const earth = new Matrix4();
    const turn = new Matrix4();
    mascot = {
      // Called every frame: the turn of the Earth, the pulse of the places, the rows of dots.
      update(phase) {
        earth.makeRotationX(tilt.rotation.x).multiply(turn.makeRotationY(spin.rotation.y));
        uniforms.uEarth.value.setFromMatrix4(earth).transpose();
        uniforms.uPhase.value = reducedMotion ? 0.3 : phase;
        const distance = camera.position.distanceTo(framing.center);
        const pixels = (body.radius / (distance * Math.tan((camera.fov * DEG) / 2))) * (container.clientHeight / 2);
        uniforms.uRows.value = rowsFor(pixels, { max: TIERS[tier].rows });
      },
    };
    container.dataset.state = 'mascot';
    await fade(0, 1);
  }
}

const container = document.querySelector('[data-globe]');
if (container) {
  start(container).catch((error) => {
    container.classList.add('globe--failed');
    console.warn(`globe: ${error.message}`);
  });
}
